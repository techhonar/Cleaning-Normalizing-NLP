"""
خط لوله پیش‌پردازش متن فارسی (Persian NLP Text Preprocessing Pipeline)
شامل دو فاز اصلی:
۱. پاک‌سازی (Cleaning): حذف نویزهای ساختاری، تگ‌های HTML، کاراکترهای نامرئی و ناشناس‌سازی اطلاعات شخصی (PII).
۲. نرمال‌سازی چهارسطحی (Normalization): یکدست‌سازی در سطوح نویسه (Character)، فاصله (Spacing)، واژه (Word) و قالب (Format).
"""

import argparse
from dataclasses import dataclass
import html
import re
import unicodedata
from typing import Dict, Any

# تعریف ثابت نیم‌فاصله استاندارد یونیکد (Zero-Width Non-Joiner)
# در UTF-8 این کاراکتر ۳ بایت اشغال می‌کند و مرز میان اجزای یک کلمه مرکب است.
ZWNJ = "\u200c"


@dataclass
class PreprocessConfig:
    """
    کلاس تنظیمات برای پیاده‌سازی «پاک‌سازی وابسته به مسئله» (Task-Dependent Cleaning).
    اینکه چه چیزی نویز محسوب می‌شود به هدف مدل بستگی دارد:
    - 'general'  : حالت استاندارد و متعادل برای پردازش‌های عمومی.
    - 'sentiment': تحلیل احساسات (حفظ ایموجی‌ها، علامت تعجب/سؤال و کشیدگی ملایم حروف).
    - 'topic'    : طبقه‌بندی موضوعی (حذف کامل ایموجی‌ها، اعداد و علائم نگارشی).
    - 'ner'      : شناسایی موجودیت‌های نامدار (حفظ دقیق اعداد، تاریخ‌ها و علائم نگارشی).
    """
    task_mode: str = "general"          # نوع مسئله: 'general', 'sentiment', 'topic', 'ner'
    use_placeholders: bool = True       # جایگزینی لینک/عدد با تگ‌های <URL> و <NUM> به جای حذف کامل
    anonymize_pii: bool = True          # ناشناس‌سازی اطلاعات شخصی (شماره موبایل و ایمیل)
    reduce_repeated_chars: bool = True  # کاهش حروف تکراری (مثلاً تبدیل «سلاااام» به «سلام»)
    fix_spacing_and_zwnj: bool = True   # اصلاح خودکار نیم‌فاصله‌ها و فاصله اطراف علائم نگارشی


class PersianTextPreprocessor:
    """کلاس اصلی پیش‌پردازش، نرمال‌سازی و ارزیابی آماری متون فارسی."""

    def __init__(self, config: PreprocessConfig = PreprocessConfig()):
        self.config = config
        # مقداردهی اولیه جدول نگاشت کاراکترها و کامپایل الگوهای Regex در لحظه ساخت شیء
        # این کار باعث می‌شود در پردازش دیتاست‌های بزرگ، الگوها هر بار از نو کامپایل نشوند.
        self._init_translation_table()
        self._init_regex_patterns()

    def _init_translation_table(self) -> None:
        """
        ساخت جدول نگاشت یک‌به‌یک نویسه‌ها (سطح اول نرمال‌سازی: سطح نویسه).
        کامپیوتر شکل ظاهری حروف را نمی‌بیند بلکه کد یونیکد (Code Point) آن‌ها را مقایسه می‌کند.
        اگر «ک» عربی و فارسی یکدست نشوند، جست‌وجوی کلمه «کتاب» نیمی از نتایج را پیدا نمی‌کند.
        """
        char_map = {
            # --- یکدست‌سازی حروف عربی با معادل استاندارد فارسی ---
            "\u064A": "\u06CC",  # تبدیل «ي» عربی (U+064A) به «ی» فارسی (U+06CC)
            "\u0649": "\u06CC",  # تبدیل «ى» الف مقصوره بدون نقطه (U+0649) به «ی» فارسی (U+06CC)
            "\u0643": "\u06A9",  # تبدیل «ك» عربی (U+0643) به «ک» فارسی (U+06A9)
            "\u0629": "\u0647",  # تبدیل «ة» گرد عربی (U+0629) به «ه» فارسی (U+0647)
            
            # --- یکدست‌سازی انواع الف‌های همزه‌دار به الف ساده (مناسب متون عمومی) ---
            "\u0623": "\u0627",  # تبدیل «أ» (U+0623) به «ا» (U+0627)
            "\u0625": "\u0627",  # تبدیل «إ» (U+0625) به «ا» (U+0627)
            "\u0671": "\u0627",  # تبدیل «ٱ» الف وصل (U+0671) به «ا» (U+0627)

            # --- یکدست‌سازی علائم نگارشی انگلیسی با معادل استاندارد فارسی ---
            "?": "؟",            # علامت سؤال انگلیسی به فارسی
            ",": "،",            # ویرگول انگلیسی به ویرگول فارسی
            ";": "؛",            # نقطه‌ویرگول انگلیسی به فارسی
            "“": "«",            # گیومه باز انگلیسی به گیومه فارسی
            "”": "»",            # گیومه بسته انگلیسی به گیومه فارسی
        }

        # --- یکدست‌سازی ارقام سهگانه (عربی، انگلیسی و فارسی) ---
        # در یونیکد، ارقام فارسی از U+06F0 (۰) تا U+06F9 (۹)
        # و ارقام عربی-هندی از U+0660 (٠) تا U+0669 (٩) قرار دارند.
        for i in range(10):
            persian_digit = chr(0x06F0 + i)
            char_map[chr(0x0660 + i)] = persian_digit  # تبدیل ارقام عربی (٠-٩) به فارسی
            char_map[str(i)] = persian_digit           # تبدیل ارقام انگلیسی (0-9) به فارسی

        # ساخت جدول ترجمه سریع در سطح C پایتون برای تابع str.translate
        self.translation_table = str.maketrans(char_map)

    def _init_regex_patterns(self) -> None:
        """کامپایل عبارات باقاعده (Regex) با توضیحات دقیق ساختار هر الگو."""

        # ۱. الگوی تگ‌های HTML: هر چیزی که با '<' شروع شود و تا اولین '>' ادامه یابد
        self.html_tag_re = re.compile(r"<[^>]+>")

        # ۲. الگوی کاراکترهای نامرئی و کنترلی مخرب:
        # شامل کاراکترهای کنترلی غیرچاپی ASCII (\x00 تا \x1f و \x7f)
        # به همراه کاراکترهای نامرئی یونیکد:
        # \u200b (ZWSP: فاصله بدون عرض)، \u200e (LRM: چپ‌به‌راست)، \u200f (RLM: راست‌به‌چپ)،
        # \u202a-\u202e (کنترل جهت متن)، \u2060 (Word Joiner)، \u00ad (Soft Hyphen)، \ufeff (BOM).
        # نکته بسیار مهم: نیم‌فاصله (\u200c - ZWNJ) و پیونددهنده ایموجی (\u200d - ZWJ)
        # عمداً در این لیست نیستند تا کلمات فارسی و ایموجی‌های ترکیبی تخریب نشوند!
        self.invisibles_re = re.compile(
            r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f\u200b\u200e\u200f\u202a-\u202e\u2060\u00ad\ufeff]"
        )

        # ۳. الگوی اعراب و کشیدگی حروف:
        # \u0640 کاراکتر تطویل یا خط کشیده (ـ) است (مثلاً در «ســـلام»).
        # بازه \u064B تا \u065F و \u0670 شامل فتحه، کسره، ضمه، تنوین‌ها، تشدید، سکون و الف خنجری است.
        self.diacritics_re = re.compile(r"[\u0640\u064B-\u065F\u0670]")

        # ۴. الگوهای شناسایی موجودیت‌های متنی و اطلاعات شخصی (PII):
        # شناسایی لینک‌های وب (شروع با http:// یا https:// یا www. تا رسیدن به اولین فاصله)
        self.url_re = re.compile(r"https?://\S+|www\.\S+")
        
        # شناسایی ساختار ایمیل (نام کاربری + @ + دامنه)
        self.email_re = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
        
        # شناسایی شماره موبایل ایران (شروع با 09، +989 یا ۰۹ به همراه ۹ رقم بعدی به انگلیسی یا فارسی)
        self.phone_re = re.compile(r"\b(?:09|\+989|۰۹)[0-9۰-۹]{9}\b")
        
        # شناسایی منشن‌های شبکه‌های اجتماعی (مانند @username)
        self.user_re = re.compile(r"@\w+")
        
        # شناسایی هشتگ‌ها: علامت '#' را بیرون پرانتز می‌گذاریم و کلمه داخل پرانتز (\w+) را در گروه ۱ می‌گیریم
        # تا بتوانیم '#' را حذف کنیم ولی خود کلمه موضوعی را در متن نگه داریم.
        self.hashtag_re = re.compile(r"#(\w+)")
        
        # شناسایی اعداد صحیح و اعشاری (پشتیبانی از هر دو نوع ارقام انگلیسی و فارسی)
        self.number_re = re.compile(r"\b[0-9۰-۹]+(?:\.[0-9۰-۹]+)?\b")

        # ۵. الگوی بازه یونیکد ایموجی‌ها و نمادهای تصویری
        self.emoji_re = re.compile(
            r"[\U0001F600-\U0001F64F\U0001F300-\U0001F5FF\U0001F680-\U0001F6FF\U0001F1E0-\U0001F1FF\u2600-\u26FF\u2700-\u27BF]+"
        )

    def clean(self, text: str) -> str:
        """
        فاز اول: پاک‌سازی متن (Text Cleaning)
        هدف: حذف یا جایگزینی نویزهای منبع داده (وب، شبکه اجتماعی) پیش از ورود به نرمال‌سازی.
        """
        # گام ۱: تبدیل Entityهای HTML به کاراکتر واقعی (مثلاً &nbsp; به فاصله یا &amp; به &)
        # این کار باید قبل از حذف تگ‌ها انجام شود.
        text = html.unescape(text)

        # گام ۲: حذف تگ‌های HTML (جایگزینی با فاصله تا کلمات چسبیده به تگ به هم نچسبند)
        text = self.html_tag_re.sub(" ", text)

        # گام ۳: حذف کاراکترهای نامرئی و کنترلی مخرب (بدون دست زدن به نیم‌فاصله)
        text = self.invisibles_re.sub("", text)

        # گام ۴: مدیریت لینک‌ها، اطلاعات شخصی (PII) و منشن‌ها
        # نکته کلیدی در ترتیب اجرا: لینک، ایمیل، موبایل و آیدی کاربر *حتماً* باید قبل از
        # مرحله جایگزینی اعداد پردازش شوند؛ زیرا داخل لینک‌ها و ایمیل‌ها اغلب عدد وجود دارد
        # (مثل ?id=45 یا @ali_89) و اگر اعداد زودتر جایگزین شوند، ساختار لینک و ایمیل می‌شکند!
        keep_links = self.config.use_placeholders
        text = self.url_re.sub(" <URL> " if keep_links else " ", text)

        if self.config.anonymize_pii:
            # ناشناس‌سازی ایمیل و شماره موبایل جهت حفظ حریم خصوصی داده‌ها
            text = self.email_re.sub(" <EMAIL> " if keep_links else " ", text)
            text = self.phone_re.sub(" <PHONE> " if keep_links else " ", text)

        text = self.user_re.sub(" <USER> " if keep_links else " ", text)

        # گام ۵: استخراج کلمه از درون هشتگ و تبدیل خط تیره زیرین (_) به فاصله
        # مثال: «#هوش_مصنوعی» تبدیل می‌شود به «هوش مصنوعی»
        text = self.hashtag_re.sub(lambda m: m.group(1).replace("_", " "), text)

        # گام ۶: تصمیم‌گیری درباره ایموجی بر اساس نوع مسئله (Task-Dependent)
        # در تحلیل احساسات ایموجی یک سرنخ قوی است و حفظ می‌شود، اما در طبقه‌بندی موضوعی نویز است.
        if self.config.task_mode == "topic":
            text = self.emoji_re.sub(" ", text)

        return text

    def normalize(self, text: str) -> str:
        """
        فاز دوم: نرمال‌سازی چهارسطحی (Text Normalization)
        هدف: تبدیل شکل‌های نوشتاری مختلفِ یک مفهوم واحد به یک شکل استاندارد تا اندازه واژگان (V) کاهش یابد.
        """

        # =====================================================================
        # سطح ۱: نرمال‌سازی در سطح نویسه و یونیکد (Character & Unicode Level)
        # =====================================================================
        # نکته مهم ترتیبی: ابتدا باید نرمال‌سازی NFKC یونیکد اجرا شود و *سپس* جدول نگاشت فارسی!
        # دلیل: در متون PDF و فونت‌های قدیمی، حروف به شکل «نمایشی عربی» (Arabic Presentation Forms)
        # ذخیره می‌شوند. استاندارد NFKC ابتدا آن‌ها را به حروف پایه تبدیل می‌کند تا جدول نگاشت ما بتواند
        # در خط بعدی «ي» و «ك» را بشناسد و به فارسی تبدیل کند. (خود NFKC به تنهایی ي عربی را فارسی نمی‌کند).
        text = unicodedata.normalize("NFKC", text)

        # اعمال جدول نگاشت (تبدیل ک/ی عربی، همزه، علائم نگارشی و ارقام به فارسی)
        text = text.translate(self.translation_table)

        # حذف اعراب (فتحه، کسره، تشدید و...) و خط کشیده (تطویل)
        text = self.diacritics_re.sub("", text)

        # =====================================================================
        # سطح ۴: نرمال‌سازی در سطح قالب برای اعداد (Format Level)
        # =====================================================================
        # اکنون که تمام ارقام انگلیسی و عربی به فارسی یکدست شده‌اند و لینک‌ها هم قبلاً به <URL> تبدیل شده‌اند،
        # می‌توانیم اعداد باقی‌مانده در متن را با خیال راحت به توکن <NUM> تبدیل کنیم.
        # استثنا: در تسک NER (شناسایی موجودیت)، تاریخ‌ها و مبالغ مالی مهم هستند و نباید حذف شوند.
        if self.config.task_mode != "ner":
            if self.config.use_placeholders:
                text = self.number_re.sub("<NUM>", text)
            elif self.config.task_mode == "topic":
                text = self.number_re.sub(" ", text)

        # =====================================================================
        # سطح ۳: نرمال‌سازی در سطح واژه (Word Level)
        # =====================================================================
        # الف) کاهش حروف تکراری غیرطبیعی:
        # الگوی (.)\1{2,} یعنی هر کاراکتری که ۳ بار یا بیشتر پشت سر هم تکرار شده باشد (مثل «سلاااام»).
        if self.config.reduce_repeated_chars and self.config.task_mode != "sentiment":
            # در حالت عادی به یک حرف کاهش می‌یابد: «سلاااام» -> «سلام»
            text = re.sub(r"(.)\1{2,}", r"\1", text)
        else:
            # در تحلیل احساسات برای حفظ شدت هیجان، حداکثر ۲ تکرار حفظ می‌شود: «سلاااام» -> «سلاام»
            text = re.sub(r"(.)\1{2,}", r"\1\1", text)

        # ب) یکدست‌سازی تکرار علائم نگارشی:
        # تبدیل سه نقطه یا بیشتر (...) به کاراکتر استاندارد سه نقطه (Horizontal Ellipsis: …)
        text = re.sub(r"\.{3,}", "…", text)
        # تبدیل تکرار علائم (مانند !!!! یا ؟؟؟؟) به یک علامت واحد (! یا ؟)
        text = re.sub(r"([!؟؛،])\1+", r"\1", text)

        # در تسک طبقه‌بندی موضوعی (Topic Classification)، علائم نگارشی کمکی نمی‌کنند و حذف می‌شوند.
        if self.config.task_mode == "topic":
            text = re.sub(r"[!؟؛،.…«»\"'()\[\]]", " ", text)

        # =====================================================================
        # سطح ۲: نرمال‌سازی در سطح فاصله و نیم‌فاصله (Spacing & ZWNJ Level)
        # =====================================================================
        if self.config.fix_spacing_and_zwnj:
            # ۱. پاک‌سازی نیم‌فاصله‌های خراب:
            # تبدیل دو یا چند نیم‌فاصله متوالی به یک نیم‌فاصله
            text = re.sub(rf"{ZWNJ}{{2,}}", ZWNJ, text)
            # اگر قبل یا بعد از نیم‌فاصله، فاصله معمولی (Space) هم تایپ شده باشد، فاصله‌ها را حذف کن
            text = re.sub(rf"\s*{ZWNJ}\s*", ZWNJ, text)

            # ۲. اتصال پیشوندهای فعلی «می» و «نمی» به فعل بعدی با نیم‌فاصله:
            # مثال: «می روم» -> «می‌روم» | «نمی دانم» -> «نمی‌دانم»
            # از Negative Lookahead (?!که|را|هم|و) استفاده شده تا اگر در متنی کلمه «می» به معنی شراب
            # قبل از کلمات ربط آمد (مثلاً «می را» یا «می و»)، به اشتباه با نیم‌فاصله به آن‌ها نچسبد!
            text = re.sub(r"\b(ن?می)\s+(?!که\b|را\b|هم\b|و\b)", rf"\1{ZWNJ}", text)

            # ۳. اتصال پسوندهای جمع، صفت تفضیلی/عالی و ضمایر ملکی با نیم‌فاصله:
            # مثال: «کتاب ها» -> «کتاب‌ها» | «بزرگ تر» -> «بزرگ‌تر» | «خانه ام» -> «خانه‌ام»
            # از Positive Lookbehind (?<=[آ-ی]) استفاده شده تا مطمئن شویم قبل از پسوند حتماً یک کلمه فارسی قرار دارد.
            # همچنین چون یک فاصله (\s+) را هدف می‌گیریم، کلماتی که خودشان با این حروف تمام می‌شوند (مثل «میز» یا «بهتر») دست‌نخورده می‌مانند.
            suffixes = r"(ها|های|هایی|تر|ترین|ام|ات|اش|مان|تان|شان)"
            text = re.sub(rf"(?<=[آ-ی])\s+{suffixes}\b", rf"{ZWNJ}\1", text)

            # ۴. استانداردسازی فاصله در اطراف علائم نگارشی:
            # قاعده نگارش: علائمی مثل ویرگول، نقطه و علامت سؤال باید به کلمه *قبلی* بچسبند و بعدشان یک فاصله باشد.
            # حذف فاصله قبل از علائم بسته‌شونده (مثلاً «سلام ، خوبی ؟» -> «سلام، خوبی؟»)
            text = re.sub(r"\s+([،؛؟!.…»)\]])", r"\1", text)
            # حذف فاصله بعد از علائم بازشونده مثل گیومه باز یا پرانتز باز (« متن » -> «متن»)
            text = re.sub(r"([«(\[])\s+", r"\1", text)
            # اضافه کردن یک فاصله بعد از علائم نگارشی در صورتی که به کلمه بعدی چسبیده باشند
            text = re.sub(r"([،؛؟!])(?=[^\s»)\]])", r"\1 ", text)

        # گام نهایی: تبدیل تمام فاصله‌ها، تب‌ها (\t) و خطوط جدید (\n) متوالی به یک فاصله استاندارد
        # و حذف فاصله‌های اضافی از ابتدا و انتهای کل رشته (strip)
        text = re.sub(r"\s+", " ", text).strip()
        return text

    def process(self, text: str) -> str:
        """اجرای زنجیره‌ای پایپ‌لاین: ابتدا پاک‌سازی (clean) و سپس نرمال‌سازی (normalize)."""
        return self.normalize(self.clean(text))

    @staticmethod
    def get_stats(text: str) -> Dict[str, Any]:
        """
        محاسبه شاخص‌های آماری متن برای مقایسه وضعیت «قبل و بعد از پیش‌پردازش»:
        - chars: طول رشته بر حسب تعداد کاراکتر.
        - tokens: تعداد کل واژه‌ها (بر اساس جداسازی با فاصله).
        - vocab_size: اندازه واژگان یا تعداد کلمات یکتا (Types / V). هدف نرمال‌سازی کاهش معقول V است.
        - persian_ratio: درصد حروف الفبای فارسی نسبت به کل حروف متن (معیاری سریع برای تشخیص زبان متن).
        """
        tokens = text.split()
        vocab = set(tokens)
        persian_chars = len(re.findall(r"[\u0600-\u06FF]", text))
        total_alpha = len(re.findall(r"\w", text))
        fa_ratio = (persian_chars / total_alpha * 100) if total_alpha > 0 else 0.0
        return {
            "chars": len(text),
            "tokens": len(tokens),
            "vocab_size": len(vocab),
            "persian_ratio": round(fa_ratio, 1),
        }

    def verify_idempotency(self, text: str) -> bool:
        """
        تست خودکار خاصیت Idempotency (تغییرناپذیری در تکرار):
        یک نرمال‌ساز استاندارد باید طوری طراحی شود که اگر خروجی آن را دوباره به خودش بدهیم،
        تغییری در متن ایجاد نشود؛ یعنی: normalize(normalize(x)) == normalize(x).
        """
        first_pass = self.process(text)
        second_pass = self.process(first_pass)
        return first_pass == second_pass


def print_report(raw_text: str, processed_text: str, preprocessor: PersianTextPreprocessor) -> None:
    """چاپ خروجی رنگ‌بندی‌شده و جدول مقایسه آماری در ترمینال برای ارائه کلاسی."""
    before = preprocessor.get_stats(raw_text)
    after = preprocessor.get_stats(processed_text)
    is_idempotent = preprocessor.verify_idempotency(raw_text)
    
    # محاسبه درصد کاهش اندازه واژگان (Vocabulary Reduction) پس از یکی شدن کلمات مشابه (مثل «كِتاب»، «کتاب» و «کتابها»)
    vocab_reduction = (
        (before["vocab_size"] - after["vocab_size"]) / before["vocab_size"] * 100
        if before["vocab_size"] else 0
    )

    # کدهای رنگ ANSI برای نمایش خواناتر در ترمینال لینوکس
    BOLD, GREEN, CYAN, YELLOW, RESET = "\033[1m", "\033[92m", "\033[96m", "\033[93m", "\033[0m"

    print(f"\n{BOLD}{CYAN}=== ۱. متن خام ورودی (Raw Text) ==={RESET}")
    print(raw_text)

    print(f"\n{BOLD}{GREEN}=== ۲. متن تمیز و نرمال‌شده (Mode: {preprocessor.config.task_mode}) ==={RESET}")
    print(processed_text)

    print(f"\n{BOLD}{YELLOW}=== ۳. گزارش آماری و تست کیفیت خط لوله ==={RESET}")
    print(f"• تعداد کاراکترها   : {before['chars']}  -->  {after['chars']}")
    print(f"• تعداد کل توکن‌ها  : {before['tokens']}  -->  {after['tokens']}")
    print(f"• اندازه واژگان (V) : {before['vocab_size']}  -->  {after['vocab_size']} (کاهش نویز واژگان: {vocab_reduction:.1f}%)")
    print(f"• نسبت حروف فارسی   : {after['persian_ratio']}%")
    print(f"• تست Idempotency   : {'✅ موفق (تغییرناپذیر در اجرای مجدد)' if is_idempotent else '❌ ناموفق'}\n")


